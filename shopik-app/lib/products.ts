// Shared product model and validation used by the form and Server Actions.
export type Product = {
  id: string;
  workspace_id: string;
  category_id: string;
  created_by: string;
  name: string;
  description: string;
  price: number;
  currency: 'UAH';
  status: 'active' | 'completed';
  created_at: string;
  updated_at: string;
};

export type ProductFields = { name: string; description: string; price: string; category_id: string; tag_ids?: string[] };
export type ProductErrors = Partial<Record<keyof ProductFields, string>>;
export type ProductResult = { ok: true } | { ok: false; error: string; fields?: ProductErrors };

// Parse decimal text as integer kopecks first; reject NaN, exponents and rounding.
export function validateProduct(input: unknown):
  | { ok: true; value: { name: string; description: string; price: number; category_id: string } }
  | { ok: false; fields: ProductErrors } {
  const fields: ProductErrors = {};
  const raw = input && typeof input === 'object' ? input as Record<string, unknown> : {};
  const name = typeof raw.name === 'string' ? raw.name.trim() : '';
  const description = typeof raw.description === 'string' ? raw.description.trim() : '';
  const priceText = typeof raw.price === 'string' ? raw.price.trim().replace(',', '.') : '';
  const category_id = raw.category_id;
  if (!isWorkspaceId(category_id)) fields.category_id = 'Виберіть категорію продукту.';
  if (!name || [...name].length > 120) fields.name = 'Вкажіть назву від 1 до 120 символів.';
  if ((raw.description !== undefined && typeof raw.description !== 'string') || [...description].length > 2000) fields.description = 'Опис має містити до 2000 символів.';
  let kopecks = 0;
  if (!/^\d{1,8}(\.\d{1,2})?$/.test(priceText)) {
    fields.price = 'Вкажіть ціну від 0 до 99 999 999,99 грн, до двох знаків після коми.';
  } else {
    const [whole, fraction = ''] = priceText.split('.');
    kopecks = Number(whole) * 100 + Number(fraction.padEnd(2, '0'));
  }
  if (Object.keys(fields).length) return { ok: false, fields };
  return { ok: true, value: { name, description, price: kopecks / 100, category_id: category_id as string } };
}

// IDs are accepted only in the formats generated by Postgres.
export function isWorkspaceId(value: unknown): value is string {
  return typeof value === 'string' && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value);
}
export function isProductId(value: unknown): value is string {
  return typeof value === 'string' && /^[0-9a-f]{64}$/.test(value);
}
